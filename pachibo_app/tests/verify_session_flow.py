snapshot('session-correction-android.png')
click('保存')
text_present('玉・メダル込みの収支 3000円')
tap(node(lambda n: 'Machine B2 22番' in n.attrib.get('text', '')))
click('明細・訂正')
click('訂正履歴・元に戻す')
click('この変更を元に戻す')
click('元に戻す')
click('閉じる')
text_present('玉・メダル込みの収支 4000円')
adb('shell', 'am', 'force-stop', PACKAGE)
adb('shell', 'am', 'start', '-n', PACKAGE+'/.MainActivity')
text_present('Machine B2 22番')
snapshot('session-flow-android.png')
adb('shell', 'am', 'force-stop', PACKAGE)
final = ROOT/'output/session-flow-result.db'
final.write_bytes(adb('exec-out', 'run-as', PACKAGE, 'cat', 'databases/ledger.db', binary=True))
with sqlite3.connect(final) as db:
    records = db.execute('SELECT state,metadata FROM sessions').fetchall()
    assert len(records) == 2 and all(state == 'ended' for state, _ in records)
    assert all(json.loads(meta)['hall'] == 'Flow Hall Fixed' for _, meta in records)
    assert db.execute('SELECT SUM(delta) FROM operations WHERE kind="cash"').fetchone()[0] == 6000
    assert db.execute('SELECT COUNT(*) FROM transfers').fetchone()[0] == 1
    assert db.execute('SELECT COUNT(*) FROM edit_history').fetchone()[0] == 2
print('UI_FLOW_PASS: account defaults, start, cash, replay, move, finish, basic edit, correction, undo and restart', flush=True)
