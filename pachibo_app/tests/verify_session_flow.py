from android_ui_helpers import *

adb('shell', 'am', 'start', '-n', PACKAGE+'/.MainActivity')
text_present('遊技を開始')
# Inspect without deleting user or fixture records; this test expects a fresh AVD.
adb('shell', 'am', 'force-stop', PACKAGE)
initial = ROOT/'output/session-flow-initial.db'
initial.write_bytes(adb('exec-out', 'run-as', PACKAGE, 'cat', 'databases/ledger.db', binary=True))
with sqlite3.connect(initial) as db:
    assert db.execute('SELECT COUNT(*) FROM sessions').fetchone()[0] == 0, 'Refusing nonempty ledger'
    assert db.execute('SELECT COUNT(*) FROM accounts').fetchone()[0] == 0, 'Refusing nonempty account list'
adb('shell', 'am', 'start', '-n', PACKAGE+'/.MainActivity')
click('ホール・交換率を登録')
click('ホールの交換率を登録')
enter('ホール', 'Flow Hall')
enter('交換率：円（例：100円）', '20')
enter('上記の円に交換できる玉・枚', '1')
click('保存')
click('遊技を開始')
tap(node(lambda n:n.attrib.get('resource-id')=='android:id/button1',False))
# The selected play date supplies both timestamps; slot is the default.
enter('ホール','Flow Hall')
enter('機種', 'Machine A')
enter('台番号', '1')
click('保存')
print('START_PASS', flush=True)
click('途中の現金投資を記録')
enter('今回追加する現金（円）', '10000')
click('保存')
click('途中の玉・メダル投資を記録')
assert node(lambda n: n.attrib.get('content-desc') == '交換率：円（例：100円）').attrib['text'] == '20'
enter('今回の口座減少（玉・枚、手数料込み）', '100')
click('保存')
click('終了して次の台へ')
enter('次の台へ持っていく玉・枚（不明なら空欄）', '600')
enter('次の機種', 'Machine B')
enter('次の台番号', '2')
click('保存')
click('遊技完了・収支を入力')
enter('現金回収（円）', '16000')
click('保存')
print('FINISH_PASS', flush=True)
tap(node(lambda n: 'Machine B 2番' in n.attrib.get('text', '')))
click('明細・訂正')
click('ホール・機種・台番号・メモを編集')
enter('ホール', 'Flow Hall Fixed')
enter('機種', 'Machine B2')
enter('台番号', '22')
